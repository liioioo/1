export function getBuiltinPromptById(id?: string, customTitle?: string, customContent?: string): string {
  if (!id || id === 'none') return '';
  if (id === 'custom') {
    const titleHeader = customTitle ? `【自定义底层提示词：${customTitle}】\n` : '';
    return (titleHeader + (customContent || '')).trim();
  }
  const item = BUILTIN_PROMPTS.find((p) => p.id === id);
  if (item) return item.prompt;

  // Check saved custom presets
  const savedList = getSavedCustomPresets();
  const saved = savedList.find((p) => p.id === id);
  if (saved) return saved.prompt;

  return '';
}

export interface SavedCustomPreset {
  id: string;
  name: string;
  shortDesc: string;
  targetPersona: string;
  prompt: string;
  createdAt?: string;
}

export function getSavedCustomPresets(): SavedCustomPreset[] {
  try {
    const raw = localStorage.getItem('custom_prompt_presets_v1');
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveCustomPresetItem(title: string, promptContent: string): SavedCustomPreset {
  const presets = getSavedCustomPresets();
  const newPreset: SavedCustomPreset = {
    id: 'custom_preset_' + Date.now(),
    name: title.trim() || '自定义预设',
    shortDesc: promptContent.trim().slice(0, 50) + (promptContent.length > 50 ? '...' : ''),
    targetPersona: '用户自定义保存的全局预设协议',
    prompt: promptContent.trim(),
    createdAt: new Date().toISOString(),
  };
  const updated = [newPreset, ...presets];
  localStorage.setItem('custom_prompt_presets_v1', JSON.stringify(updated));
  return newPreset;
}

export function deleteSavedCustomPreset(id: string): void {
  const presets = getSavedCustomPresets();
  const updated = presets.filter((p) => p.id !== id);
  localStorage.setItem('custom_prompt_presets_v1', JSON.stringify(updated));
}
